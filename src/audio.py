"""Reel 1 soundtrack + sound design (120 BPM), synthesized from scratch.

Nothing here is sampled or licensed from a third party: every drum, synth,
splash, ice clink, fizz, can-crack, zap and whoosh is generated by code (see
synth.py), so the audio is 100% original and free to use commercially.

Output: output/build/audio_mix.wav (48 kHz, 16-bit stereo)
"""
import os
import numpy as np
from scipy import signal
import timeline as TL
from synth import *  # noqa: F401,F403
from synth import rng, SR

N = int(SR * TL.DURATION)
OUT = os.path.join(os.path.dirname(__file__), "..", "output", "build")
os.makedirs(OUT, exist_ok=True)


# ================================================================== arrangement
drums, bass, music, sfx, send = Bus(N), Bus(N), Bus(N), Bus(N), Bus(N)
kick_times = []

CH = {  # chord voicings (MIDI)
    "Fm": [53, 56, 60, 65, 68],
    "Db": [49, 53, 56, 61, 65],
    "Ab": [51, 56, 60, 63, 68],
    "Eb": [51, 55, 58, 63, 67],
}
ROOT = {"Fm": 29, "Db": 37, "Ab": 32, "Eb": 39}
PROG = ["Fm", "Db", "Ab", "Eb"]


def T(bar, s16, base=TL.DROP):
    return base + bar * TL.BAR + s16 * TL.S16


# ---------- INTRO (0 - 3.0)
music.add(pad(CH["Fm"], 2.85, cutoff=650, att=0.9, rel=0.12), 0.0, 0.55)
music.add(pad([m + 12 for m in CH["Fm"]], 1.6, cutoff=2400, att=1.4, rel=0.12), 1.3, 0.25)
bass.add(sub808(mtof(29), 2.85), 0.0, 0.35)
for t0, _ in TL.INTRO_WORDS:
    sfx.add(whoosh(0.32, 400, 5000, peak=0.85, pan_from=-0.5, pan_to=0.3), t0 - 0.27, 0.35)
    drums.add(low_hit(), t0, 0.95)
    send.add(low_hit(), t0, 0.35)
    drums.add(clap(), t0, 0.35)
    send.add(clap(), t0, 0.5)
sfx.add(riser(1.95), 0.95, 0.42)
# snare roll build 2.0 -> 2.9
roll = [2.0 + i * 0.125 for i in range(4)] + [2.5 + i * 0.0625 for i in range(4)] + [2.75 + i * 0.03125 for i in range(5)]
for i, t0 in enumerate(roll):
    drums.add(snare(0.6 + 0.4 * i / len(roll)), t0, 0.18 + 0.4 * i / len(roll))
sfx.add(reverse_cymbal(1.2), TL.DROP - 1.2, 0.55)
sfx.add(whoosh(0.4, 600, 9000, peak=0.95, pan_from=0, pan_to=0), TL.DROP - 0.4, 0.35)

# ---------- MAIN GROOVE (3.0 - 19.0) : 8 bars
KICKS_A = [0, 3, 8, 10]
KICKS_B = [0, 3, 8, 11, 14]
for bar in range(8):
    chord = PROG[bar % 4]
    kicks = KICKS_A if bar % 2 == 0 else KICKS_B
    for s in kicks:
        drums.add(kick(), T(bar, s), 1.0)
        kick_times.append(T(bar, s))
    # 808 follows the kick
    for i, s in enumerate(kicks):
        nxt = kicks[i + 1] if i + 1 < len(kicks) else 16
        dur = (nxt - s) * TL.S16
        glide = None
        if bar % 2 == 1 and i == len(kicks) - 1:
            glide = mtof(ROOT[PROG[(bar + 1) % 4]])
        bass.add(sub808(mtof(ROOT[chord]), dur, glide), T(bar, s), 0.85)
    for s in (4, 12):
        drums.add(clap(), T(bar, s), 0.62)
        send.add(clap(), T(bar, s), 0.35)
    for s in range(0, 16, 2):
        drums.add(hat(), T(bar, s), 0.32 if s % 4 == 0 else 0.22, pan=0.25)
    if bar % 2 == 1:   # hat roll into each scene change
        for k in range(8):
            drums.add(hat(), T(bar, 12 + k * 0.5), 0.12 + 0.03 * k, pan=0.25)
    else:
        for s in (5, 13):
            drums.add(hat(), T(bar, s), 0.13, pan=-0.2)
    drums.add(hat(True), T(bar, 14), 0.2, pan=-0.15)
    # supersaw hook (3-3-2 rhythm)
    hits = [0, 3, 6, 8, 11, 14] if bar % 2 == 0 else [0, 3, 6, 10, 12]
    for s in hits:
        d = 0.16 if s != 12 else 0.42
        st = chord_stab(CH[chord], d, bright=1.0)
        music.add(st, T(bar, s), 0.42)
        send.add(st, T(bar, s), 0.16)
    # sidechained pad
    music.add(pad(CH[chord], TL.BAR, cutoff=1500, att=0.05, rel=0.1), T(bar, 0), 0.30)
    # arp layer in scenes 2 and 4
    if bar in (2, 3, 6, 7):
        tones = sorted(CH[chord])[1:] + [CH[chord][1] + 12]
        pattern = [0, 1, 2, 3, 4, 3, 2, 1]
        for s in range(16):
            m = tones[pattern[s % 8] % len(tones)] + 12
            p = pluck(m, 0.11)
            music.add(p, T(bar, s), 0.16, pan=-0.35 if s % 2 else 0.35)
            send.add(p, T(bar, s), 0.08)

# scene changes: crash + impact
for t0 in TL.DRINK_STARTS:
    big = t0 == TL.DROP
    sfx.add(impact(1.2 if big else 0.7), t0, 1.0 if big else 0.6)
    send.add(impact(1.0), t0, 0.35 if big else 0.2)
    drums.add(crash(), t0, 0.55)
    send.add(crash(), t0, 0.2)

# ---------- SCENE 1 : Cherry Limeade (explosive splash)
sfx.add(splash(1.4, 2.0), TL.DROP, 0.95)
send.add(splash(1.0, 2.0), TL.DROP, 0.25)
sfx.add(whoosh(0.35, 300, 5000, peak=0.8), TL.CUT_S1[0] - 0.3, 0.45)
drums.add(low_hit(0.6), TL.CUT_S1[0], 0.45)
sfx.add(can_open(), TL.CAN_OPEN_S1 - 0.04, 0.85)
send.add(can_open(), TL.CAN_OPEN_S1 - 0.04, 0.2)
sfx.add(fizz(1.2), TL.CAN_OPEN_S1 + 0.06, 0.5)
# rainbow wave surge (transition 1 -> 2)
sfx.add(whoosh(0.42, 180, 3500, peak=0.9, pan_from=0, pan_to=0), TL.WAVE_START - 0.04, 0.6)
sfx.add(splash(1.2, 1.4), 6.92, 0.75)

# ---------- SCENE 2 : Rainbow Candy (colourful liquid wave)
sfx.add(gurgle(0.7), 7.05, 0.5)
for t0, f0 in [(7.62, 420), (8.05, 560), (8.38, 480), (9.22, 620), (9.6, 380), (10.2, 520)]:
    sfx.add(bloop(f0), t0, 0.32, pan=rng.uniform(-0.6, 0.6))
    send.add(bloop(f0), t0, 0.12)
sfx.add(whoosh(0.3, 300, 5000, peak=0.8, pan_from=0.6, pan_to=-0.6), TL.CUT_S2[0] - 0.26, 0.45)
drums.add(low_hit(0.6), TL.CUT_S2[0], 0.4)
sfx.add(fizz(1.6, 1800), TL.CUT_S2[0] + 0.05, 0.3)
sfx.add(whoosh(0.28, 500, 9000, peak=0.75, pan_from=0.8, pan_to=-0.9), TL.WHIP_OUT_S2 - 0.02, 0.75)

# ---------- SCENE 3 : Green Apple (ice + cold mist)
sfx.add(whoosh(0.3, 600, 8000, peak=0.2, pan_from=0.9, pan_to=0), 11.0, 0.5)
sfx.add(wind(4.0), 11.0, 0.10)
for i, t0 in enumerate(TL.ICE_HITS):
    sfx.add(ice_clink(amp=0.8), t0, 0.5, pan=rng.uniform(-0.6, 0.6))
    sfx.add(ice_clink(amp=0.5), t0 + rng.uniform(0.03, 0.07), 0.3, pan=rng.uniform(-0.6, 0.6))
    send.add(ice_clink(), t0, 0.15)
sfx.add(whoosh(0.3, 300, 5000, peak=0.8), TL.CUT_S3[0] - 0.26, 0.4)
drums.add(low_hit(0.6), TL.CUT_S3[0], 0.4)
for k in range(3):
    sfx.add(ice_clink(amp=0.6), TL.CUT_S3[0] + 0.05 + k * 0.07, 0.35, pan=rng.uniform(-0.5, 0.5))
sfx.add(can_open(), TL.CAN_OPEN_S3 - 0.04, 0.85)
send.add(can_open(), TL.CAN_OPEN_S3 - 0.04, 0.2)
sfx.add(fizz(1.2), TL.CAN_OPEN_S3 + 0.06, 0.45)
sfx.add(riser(0.32), TL.ZOOM_OUT_S3 - 0.04, 0.5)
sfx.add(whoosh(0.3, 400, 10000, peak=0.95, pan_from=0, pan_to=0), TL.ZOOM_OUT_S3 - 0.02, 0.6)

# ---------- SCENE 4 : Banana Pineapple (electric)
sfx.add(thunder(2.2), 15.0, 0.75)
send.add(thunder(2.2), 15.0, 0.2)
for t0 in TL.STRIKES_S4:
    big = t0 in (15.0, 18.0)
    z = zap(0.6 if big else 0.35, big)
    sfx.add(z, t0, 0.55 if big else 0.36, pan=rng.uniform(-0.5, 0.5))
    send.add(z, t0, 0.12)
hum_n = int(3.7 * SR)
hum_t = ta(hum_n)
hum = filt(sos_bp(80, 900), np.sign(np.sin(2 * np.pi * 60 * hum_t)) * 0.5 + saw(120, hum_n) * 0.3)
hum *= np.clip(hum_t / 0.3, 0, 1) * np.clip((3.7 - hum_t) / 0.3, 0, 1) * (0.7 + 0.3 * np.sin(2 * np.pi * 7 * hum_t))
sfx.add(hum, 15.05, 0.08)
for t0 in TL.CUT_S4[:2]:
    sfx.add(whoosh(0.22, 500, 7000, peak=0.85), t0 - 0.2, 0.4)
sfx.add(riser(0.75), 18.0, 0.4)
sfx.add(whoosh(0.3, 300, 9000, peak=0.9, pan_from=0, pan_to=0), TL.WHIP_OUT_S4 - 0.05, 0.75)

# ---------- END CARD (19.0 - 24.5)
E = TL.END_START
sfx.add(impact(1.1), E, 0.9)
send.add(impact(1.0), E, 0.3)
drums.add(crash(3.0), E, 0.5)
send.add(crash(3.0), E, 0.25)
st = chord_stab(CH["Fm"], 0.9)
music.add(st, E, 0.5)
send.add(st, E, 0.3)
music.add(pad(CH["Fm"], 2.0, cutoff=1800, att=0.05, rel=0.2), E, 0.32)
music.add(pad(CH["Db"], 1.0, cutoff=1800, att=0.05, rel=0.2), E + 2.0, 0.32)
music.add(pad(CH["Eb"], 1.0, cutoff=1800, att=0.05, rel=0.2), E + 3.0, 0.32)
bass.add(sub808(mtof(29), 1.9), E, 0.8)
bass.add(sub808(mtof(37), 0.95), E + 2.0, 0.75)
bass.add(sub808(mtof(39), 0.95, glide_to=mtof(41)), E + 3.0, 0.75)
for bar in range(2):
    for s in (0, 7, 10):
        drums.add(kick(), T(bar, s, E), 0.85)
        kick_times.append(T(bar, s, E))
    drums.add(clap(), T(bar, 12, E), 0.5)
    send.add(clap(), T(bar, 12, E), 0.3)
    for s in range(0, 16, 2):
        drums.add(hat(), T(bar, s, E), 0.18, pan=0.25)
    chord = ["Fm", "Db"][bar] if bar == 0 else None
    seq = [CH["Fm"]] * 16 if bar == 0 else [CH["Db"]] * 8 + [CH["Eb"]] * 8
    for s in range(16):
        tones = sorted(seq[s])[1:] + [seq[s][1] + 12]
        m = tones[[0, 1, 2, 3, 4, 3, 2, 1][s % 8] % len(tones)] + 12
        p = pluck(m, 0.11)
        music.add(p, T(bar, s, E), 0.14, pan=-0.35 if s % 2 else 0.35)
        send.add(p, T(bar, s, E), 0.08)
# text entrance accents
drums.add(low_hit(), TL.END_NAME, 0.8)
sfx.add(whoosh(0.35, 500, 7000, peak=0.6), TL.END_SUB - 0.15, 0.35)
sfx.add(whoosh(0.3, 800, 9000, peak=0.6, pan_from=0.5, pan_to=-0.5), TL.END_ADDR - 0.1, 0.25)
music.add(bell(89, 1.5), TL.END_CTA, 0.22)
music.add(bell(96, 1.5), TL.END_CTA + 0.06, 0.15)
send.add(bell(89, 1.5), TL.END_CTA, 0.2)
for t0 in TL.END_SHINES:
    sp = sparkle(0.6, 9)
    sfx.add(sp, t0, 0.45)
    send.add(sp, t0, 0.25)
# final hit at 23.0 + ring out
FIN = E + 2 * TL.BAR
drums.add(kick(), FIN, 0.9)
kick_times.append(FIN)
sfx.add(impact(1.0, 1.5), FIN, 0.55)
st = chord_stab(CH["Fm"] + [72], 1.3)
music.add(st, FIN, 0.55)
send.add(st, FIN, 0.45)
music.add(pad(CH["Fm"], 1.3, cutoff=2200, att=0.02, rel=0.2), FIN, 0.35)
bass.add(sub808(mtof(29), 1.3), FIN, 0.85)
drums.add(crash(1.5), FIN, 0.45)

# ================================================================== mix
duck = np.ones(N)
for kt in kick_times:
    i0 = int(kt * SR)
    m = min(N - i0, int(0.35 * SR))
    tt = ta(m)
    duck[i0:i0 + m] = np.minimum(duck[i0:i0 + m], 1 - 0.55 * np.exp(-tt / 0.09))
duck = signal.lfilter([0.02], [1, -0.98], duck)  # soften
music.b *= duck[:, None]
send_ducked = send.b * (0.5 + 0.5 * duck[:, None])

ir = make_ir(1.9)
wet = reverb(send_ducked, ir)
wet += pingpong(music.b * 1.2)

mix = drums.b * 0.9 + bass.b * 0.7 + music.b * 3.4 + sfx.b * 1.0 + wet * 0.6
mix = filt(sos_hp(28), mix)

# gentle tilt: a little air on top
mix += filt(sos_hp(8000), mix) * 0.12

# final fade
t = ta(N)
fade = np.clip((TL.DURATION - t) / 0.75, 0, 1)
mix *= fade[:, None]

# look-ahead peak limiter
from scipy.ndimage import maximum_filter1d
mix /= np.max(np.abs(mix)) + 1e-9
mix *= 2.0  # drive into limiter
look = int(0.003 * SR)
peak = maximum_filter1d(np.abs(mix).max(1), size=2 * look + 1)
thr = 0.89
g = np.minimum(1.0, thr / (peak + 1e-9))
# smooth gain: fast attack (already via look-ahead window), ~80 ms release
g_s = np.copy(g)
alpha = np.exp(-1 / (0.08 * SR))
g_s = signal.lfilter([1 - alpha], [1, -alpha], g)
g_s = np.minimum(g_s, g)
g_s = np.minimum(g_s, maximum_filter1d(g_s, 1))
mix *= g_s[:, None]
mix = np.tanh(mix * 1.05) / np.tanh(1.05) * 0.84
mix = np.clip(mix, -0.89, 0.89)

from scipy.io import wavfile
wavfile.write(os.path.join(OUT, "audio_mix.wav"), SR, (mix * 32767).astype(np.int16))
for name, bus, gn in [("drums", drums, 0.9), ("bass", bass, 0.7), ("music", music, 3.4), ("sfx", sfx, 1.0)]:
    r = np.sqrt(((bus.b * gn) ** 2).mean())
    print(f"{name:6s} rms={20*np.log10(r+1e-12):6.1f} dB peak={np.abs(bus.b).max():.2f}")
print("wrote", os.path.join(OUT, "audio_mix.wav"), f"{TL.DURATION}s")
